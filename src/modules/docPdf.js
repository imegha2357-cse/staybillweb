// A plain A4 document (purchase order, payslip, credit note, register):
// hotel header, title + number, two columns of details, a table and totals.
import { saveFile } from '../platform';

export const rs = (n) => `Rs. ${Number(n || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/**
 * spec: { settings, title, number, left:[[label,value]], right:[[label,value]],
 *         head:[], body:[[]], totals:[[label,value,bold?]], notes, sign, filename, landscape }
 */
export async function buildDocPdf(spec) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: spec.landscape ? 'landscape' : 'portrait' });
  const W = doc.internal.pageSize.getWidth();
  const s = spec.settings || {};
  const teal = [0, 95, 115];
  doc.setFillColor(...teal); doc.rect(0, 0, W, 4, 'F');
  doc.setFont('helvetica', 'bold'); doc.setFontSize(15); doc.setTextColor(20, 30, 40);
  doc.text(s.hotelName || 'Hotel', 14, 16);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(90);
  const addr = [s.address, s.city, s.state, s.pincode].filter(Boolean).join(', ');
  let y = 21;
  if (addr) { doc.text(addr, 14, y); y += 4; }
  const contact = [s.phone, s.email, s.gstin && `GSTIN ${s.gstin}`].filter(Boolean).join('  ·  ');
  if (contact) { doc.text(contact, 14, y); y += 4; }
  doc.setFont('helvetica', 'bold'); doc.setFontSize(13); doc.setTextColor(...teal);
  doc.text(spec.title.toUpperCase(), W - 14, 16, { align: 'right' });
  if (spec.number) { doc.setFontSize(10); doc.setTextColor(40); doc.text(spec.number, W - 14, 22, { align: 'right' }); }
  y = Math.max(y, 26) + 3;
  doc.setDrawColor(220); doc.line(14, y, W - 14, y); y += 6;
  const col = (rows, x) => {
    let yy = y;
    (rows || []).forEach(([k, v]) => {
      if (v === undefined || v === null || v === '') return;
      doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(110); doc.text(String(k), x, yy);
      doc.setFont('helvetica', 'bold'); doc.setFontSize(9.5); doc.setTextColor(25);
      const lines = doc.splitTextToSize(String(v), W / 2 - 24);
      doc.text(lines, x, yy + 4); yy += 5 + lines.length * 4;
    });
    return yy;
  };
  y = Math.max(col(spec.left, 14), col(spec.right, W / 2 + 4)) + 2;
  if (spec.head) {
    autoTable(doc, {
      startY: y, head: [spec.head], body: spec.body || [],
      styles: { fontSize: 8.5, cellPadding: 2 }, headStyles: { fillColor: teal, textColor: 255 },
      columnStyles: spec.columnStyles || {}, margin: { left: 14, right: 14 },
    });
    y = doc.lastAutoTable.finalY + 6;
  }
  (spec.totals || []).forEach(([k, v, bold]) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal'); doc.setFontSize(bold ? 11 : 9.5); doc.setTextColor(25);
    doc.text(String(k), W - 70, y); doc.text(String(v), W - 14, y, { align: 'right' }); y += bold ? 7 : 5.5;
  });
  if (spec.notes) {
    y += 4; doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(80);
    doc.text(doc.splitTextToSize(spec.notes, W - 28), 14, y);
  }
  const H = doc.internal.pageSize.getHeight();
  if (spec.sign) {
    doc.setDrawColor(160); doc.line(W - 74, H - 30, W - 14, H - 30);
    doc.setFontSize(8.5); doc.setTextColor(90); doc.text(spec.sign, W - 44, H - 25, { align: 'center' });
  }
  doc.setFontSize(7.5); doc.setTextColor(150); doc.text('Generated by StayBill', 14, H - 8);
  return doc;
}

export async function docPdf(spec) {
  const doc = await buildDocPdf(spec);
  await saveFile(spec.filename || `${spec.number || spec.title}.pdf`, doc.output('blob'), 'application/pdf');
}
